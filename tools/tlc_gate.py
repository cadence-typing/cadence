#!/usr/bin/env python3
"""TLC gate over the living model registry `models/claims.toml` (RFC
2026-11-26-formal-gates-and-production-mapping, issue #28).

For every registered model the positive configuration must finish with
"No error has been found", and every mutant configuration must fail on the
invariant it is registered to violate. A missing tool, a jar digest
mismatch, a timeout, an unparsable result, zero models, an unresolved
production symbol or runtime test, a stale registry snapshot or a stale
protocol table in docs/TAUTEN.md is a failure. Results are bounded:
the strongest badge this gate can give is `model-proved`.

The frozen handover runner `tools/run_models.py` is pinned by
MANIFEST.sha256 and stays as it is; this gate never writes under
`formal/` or `evidence/`.

Usage:
  tlc_gate.py             run the gate (TLA2TOOLS_JAR must name the pinned jar)
  tlc_gate.py --update    rewrite models/claims.json and the docs table from
                          the registry; refuses a weakening without [[amend]]
"""
from __future__ import annotations

import dataclasses
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from typing import Callable

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = Path("models/claims.toml")
SNAPSHOT = Path("models/claims.json")
DOCS = Path("docs/TAUTEN.md")
DOCS_BEGIN = "<!-- models:begin (generated by tools/tlc_gate.py --update) -->"
DOCS_END = "<!-- models:end -->"
TOOL_ENV = "TLA2TOOLS_JAR"
EVIDENCE_ENV = "CADENCE_EVIDENCE_DIR"
# TLC 1.7.4, the release the handover pinned (tools/run_models.py) and the
# one docker/Dockerfile adds by the same digest.
TOOL_SHA256 = "936a262061c914694dfd669a543be24573c45d5aa0ff20a8b96b23d01e050e88"
# Per configuration. The largest current model explores a few hundred
# states in about two seconds; a minute leaves room for JVM start-up on a
# loaded CI runner while still catching a model whose state space exploded.
MODEL_TIMEOUT_SECONDS = 60
# A model may ask for more (`timeout_seconds`), never more than this.
MAX_MODEL_TIMEOUT_SECONDS = 600
STATUSES = ("mapped", "design-probe")


class GateError(Exception):
    """A failed or blocked gate. Never a pass."""


@dataclasses.dataclass(frozen=True)
class Outcome:
    returncode: int
    log: str


Runner = Callable[[Path, str, str, int], Outcome]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# ---------------------------------------------------------------- registry

def load_registry(root: Path) -> dict:
    path = root / REGISTRY
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as error:
        raise GateError(f"{REGISTRY}: {error}") from error
    models = data.get("model", [])
    if not models:
        raise GateError(f"{REGISTRY}: zero models registered; a gate over nothing is not a pass")
    seen = set()
    for model in models:
        name = model.get("module")
        if not name or name in seen:
            raise GateError(f"{REGISTRY}: missing or duplicate module {name!r}")
        seen.add(name)
        for key in ("dir", "config", "invariants", "status"):
            if not model.get(key):
                raise GateError(f"{name}: missing `{key}`")
        timeout = model.get("timeout_seconds", MODEL_TIMEOUT_SECONDS)
        if not isinstance(timeout, int) or not 1 <= timeout <= MAX_MODEL_TIMEOUT_SECONDS:
            raise GateError(f"{name}: timeout_seconds must be 1..{MAX_MODEL_TIMEOUT_SECONDS}")
        if model["status"] not in STATUSES:
            raise GateError(f"{name}: status must be one of {STATUSES}")
        if model["status"] == "mapped":
            for key in ("production_symbols", "runtime_tests", "mutant"):
                if not model.get(key):
                    raise GateError(f"{name}: a `mapped` model needs `{key}`")
        elif not model.get("blocked_on"):
            raise GateError(f"{name}: a `design-probe` model names what it is `blocked_on`")
        for mutant in model.get("mutant", []):
            if mutant.get("violates") not in model["invariants"] + model.get("properties", []):
                raise GateError(f"{name}: mutant {mutant.get('config')!r} must violate a registered invariant or property")
    for amend in data.get("amend", []):
        if not amend.get("module") or not str(amend.get("reason", "")).strip():
            raise GateError(f"{REGISTRY}: every [[amend]] names a module and a reason")
    return data


def config_constants(text: str) -> str:
    match = re.search(r"^CONSTANTS?\s+(.*?)(?=^\w|\Z)", text, re.M | re.S)
    return " ".join(match[1].split()) if match else ""


def config_invariants(text: str) -> set[str]:
    found = set()
    for match in re.finditer(r"^INVARIANTS?\s+(.*?)(?=^\w|\Z)", text, re.M | re.S):
        found.update(match[1].split())
    return found


def config_properties(text: str) -> set[str]:
    found = set()
    for match in re.finditer(r"^PROPERT(?:Y|IES)\s+(.*?)(?=^\w|\Z)", text, re.M | re.S):
        found.update(match[1].split())
    return found


def config_checks(text: str) -> set[str]:
    return config_invariants(text) | config_properties(text)


def check_configs(model: dict, directory: Path) -> None:
    """A registered invariant or temporal property must be one the
    configuration checks."""
    positive = read(directory / model["config"])
    missing = set(model["invariants"]) - config_invariants(positive)
    missing |= set(model.get("properties", [])) - config_properties(positive)
    if missing:
        raise GateError(f"{model['module']}: {model['config']} does not check {sorted(missing)}")
    for mutant in model.get("mutant", []):
        if mutant["violates"] not in config_checks(read(directory / mutant["config"])):
            raise GateError(f"{model['module']}: {mutant['config']} does not check {mutant['violates']}")


def record(data: dict, root: Path) -> dict:
    """The committed snapshot: what each model claims, with input digests."""
    models = []
    for model in data["model"]:
        directory = root / model["dir"]
        check_configs(model, directory)
        configs = [model["config"]] + [m["config"] for m in model.get("mutant", [])]
        models.append({
            "module": model["module"],
            "status": model["status"],
            "invariants": sorted(model["invariants"]),
            "properties": sorted(model.get("properties", [])),
            "mutants": sorted(f"{m['config']} violates {m['violates']}" for m in model.get("mutant", [])),
            "production_symbols": sorted(model.get("production_symbols", [])),
            "runtime_tests": sorted(model.get("runtime_tests", [])),
            "constants": config_constants(read(directory / model["config"])),
            "sha256": {name: sha256(directory / name)
                       for name in [f"{model['module']}.tla"] + configs},
        })
    return {"schema_version": 1, "tool": "TLC 1.7.4", "tool_sha256": TOOL_SHA256, "models": models}


def weakenings(old: dict, new: dict, amended: set[str]) -> list[str]:
    """Registry ratchet: a model may not disappear or lose an invariant,
    mutant, symbol or test, or drop from mapped, unless amended."""
    found = []
    current = {m["module"]: m for m in new["models"]}
    for before in old.get("models", []):
        name = before["module"]
        if name in amended:
            continue
        after = current.get(name)
        if after is None:
            found.append(f"{name}: removed")
            continue
        for key in ("invariants", "properties", "mutants", "production_symbols", "runtime_tests"):
            lost = set(before.get(key, [])) - set(after.get(key, []))
            if lost:
                found.append(f"{name}: {key} lost {sorted(lost)}")
        if before["status"] == "mapped" and after["status"] != "mapped":
            found.append(f"{name}: no longer mapped")
    return found


def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise GateError(f"{path}: {error}") from error


# -------------------------------------------------------------- docs table

def badge(model: dict) -> str:
    return "model-proved (bounded)" if model["status"] == "mapped" else "design-probe (not mapped)"


def docs_table(data: dict) -> str:
    rows = ["| Model | Invariants | Mutants that must fail | Production symbols | Badge |",
            "|---|---|---|---|---|"]
    for model in data["model"]:
        mutants = "<br>".join(f"`{m['config']}` → `{m['violates']}`" for m in model.get("mutant", [])) or "—"
        symbols = "<br>".join(f"`{s}`" for s in model.get("production_symbols", [])) or f"none; blocked on {model.get('blocked_on')}"
        checked = ", ".join(model["invariants"] + [f"{p} (temporal)" for p in model.get("properties", [])])
        rows.append(f"| `{model['dir']}/{model['module']}.tla` | {checked} "
                    f"| {mutants} | {symbols} | {badge(model)} |")
    return "\n".join([DOCS_BEGIN, *rows, DOCS_END])


def docs_section(text: str) -> tuple[int, int]:
    start, end = text.find(DOCS_BEGIN), text.find(DOCS_END)
    if start < 0 or end < start:
        raise GateError(f"{DOCS}: protocol table markers are missing")
    return start, end + len(DOCS_END)


# ----------------------------------------------------- symbols and tests

def crate_sources(root: Path) -> dict[str, Path]:
    run = subprocess.run(["cargo", "metadata", "--offline", "--no-deps", "--format-version", "1"],
                         cwd=root, capture_output=True, text=True, check=False)
    if run.returncode != 0:
        raise GateError(f"cargo metadata failed: {run.stderr.strip()[-400:]}")
    crates = {}
    for package in json.loads(run.stdout)["packages"]:
        for target in package["targets"]:
            if "lib" in target["kind"]:
                crates[target["name"]] = Path(target["src_path"]).parent
    return crates


def expand(symbol: str) -> list[str]:
    match = re.fullmatch(r"(.*)::\{(.*)\}", symbol)
    if not match:
        return [symbol]
    return [f"{match[1]}::{part.strip()}" for part in match[2].split(",") if part.strip()]


ITEM = r"\b(?:fn|struct|enum|trait|type|const|static|mod)\s+{name}\b"


def resolve(symbol: str, crates: dict[str, Path]) -> bool:
    """True when the named item is defined in the crate it names. Module
    segments follow files; a trailing `Type::method` is accepted when some
    file in that module path defines the type and a `fn method`."""
    crate, *path = symbol.split("::")
    source = crates.get(crate)
    if source is None or not path:
        return False
    directory, files = source, [source / "lib.rs"]
    for index, segment in enumerate(path[:-1]):
        nested = [directory / f"{segment}.rs", directory / segment / "mod.rs"]
        found = [f for f in nested if f.is_file()]
        if found:
            directory, files = directory / segment, found
            continue
        # A type, not a module: the rest is `Type::method`.
        rest = path[index:]
        if len(rest) != 2:
            return False
        candidates = set(files) | (set(directory.rglob("*.rs")) if directory.is_dir() else set())
        texts = [f.read_text(encoding="utf-8") for f in sorted(candidates)]
        return (any(re.search(ITEM.format(name=re.escape(rest[0])), t) for t in texts)
                and any(re.search(r"impl\b[^{]*\b" + re.escape(rest[0]) + r"\b", t)
                        and re.search(r"\bfn\s+" + re.escape(rest[1]) + r"\b", t) for t in texts))
    pattern = ITEM.format(name=re.escape(path[-1]))
    return any(f.is_file() and re.search(pattern, f.read_text(encoding="utf-8")) for f in files)


def listed_tests(root: Path, package: str) -> set[str]:
    run = subprocess.run(["cargo", "test", "--locked", "-q", "-p", package, "--", "--list", "--format", "terse"],
                         cwd=root, capture_output=True, text=True, check=False)
    if run.returncode != 0:
        raise GateError(f"cargo test --list for {package} failed: {run.stderr.strip()[-400:]}")
    return {line.rsplit(": ", 1)[0] for line in run.stdout.splitlines() if line.endswith(": test")}


def check_mapping(data: dict, root: Path, crates: dict[str, Path] | None = None,
                  lister: Callable[[Path, str], set[str]] = listed_tests) -> list[str]:
    models = [m for m in data["model"] if m.get("production_symbols") or m.get("runtime_tests")]
    if not models:
        return []
    errors, listings = [], {}
    crates = crate_sources(root) if crates is None else crates
    for model in models:
        for symbol in (s for entry in model.get("production_symbols", []) for s in expand(entry)):
            if not resolve(symbol, crates):
                errors.append(f"{model['module']}: production symbol {symbol} not found")
        for test in model.get("runtime_tests", []):
            package, _, name = test.partition("::")
            if package not in listings:
                listings[package] = lister(root, package)
            if name not in listings[package]:
                errors.append(f"{model['module']}: runtime test {test} not found")
    return errors


# ------------------------------------------------------------------- TLC

def tlc_runner(jar: Path) -> Runner:
    def run(directory: Path, module: str, config: str, timeout: int = MODEL_TIMEOUT_SECONDS) -> Outcome:
        with tempfile.TemporaryDirectory(prefix="cadence-tlc-") as scratch:
            work = Path(scratch) / "model"
            shutil.copytree(directory, work)
            command = ["java", "-XX:+UseParallelGC", "-Xmx512m", "-cp", str(jar), "tlc2.TLC",
                       "-workers", "1", "-config", config, "-metadir", str(Path(scratch) / "meta"), module]
            try:
                done = subprocess.run(command, cwd=work, text=True, stdout=subprocess.PIPE,
                                      stderr=subprocess.STDOUT, timeout=timeout, check=False)
            except subprocess.TimeoutExpired as error:
                raise GateError(f"{config}: timed out after {timeout}s; a timeout is not a result") from error
            except OSError as error:
                raise GateError(f"cannot run java: {error}") from error
            return Outcome(done.returncode, done.stdout)
    return run


def judge(model: dict, config: str, expected: str | None, outcome: Outcome) -> dict:
    counts = re.search(r"(\d+) states generated, (\d+) distinct states found", outcome.log)
    if expected is None:
        passed = outcome.returncode == 0 and "Model checking completed. No error has been found." in outcome.log
    elif expected in model.get("properties", []):
        # TLC does not name the temporal property it refutes, so a mutant
        # configuration that expects one checks that property alone.
        violated = re.findall(r"Invariant (\w+) is violated", outcome.log)
        passed = (outcome.returncode != 0 and not violated and "State 1:" in outcome.log
                  and "Temporal properties were violated" in outcome.log)
    else:
        violated = re.findall(r"Invariant (\w+) is violated", outcome.log)
        passed = outcome.returncode != 0 and violated == [expected] and "State 1:" in outcome.log
    return {"module": model["module"], "config": config, "expected_violation": expected,
            "passed": passed, "returncode": outcome.returncode,
            "distinct_states": int(counts[2]) if counts else None,
            "log_tail": None if passed else outcome.log[-4000:]}


def run_models(data: dict, root: Path, runner: Runner) -> list[dict]:
    results = []
    for model in data["model"]:
        directory = root / model["dir"]
        cases = [(model["config"], None)] + [(m["config"], m["violates"]) for m in model.get("mutant", [])]
        for config, expected in cases:
            timeout = model.get("timeout_seconds", MODEL_TIMEOUT_SECONDS)
            results.append(judge(model, config, expected, runner(directory, model["module"], config, timeout)))
    return results


def jar_from_env() -> Path:
    supplied = os.environ.get(TOOL_ENV)
    if not supplied:
        raise GateError(f"{TOOL_ENV} is unset; the TLC gate is blocked, not passed")
    jar = Path(supplied)
    if not jar.is_file():
        raise GateError(f"{TOOL_ENV}={supplied} does not exist")
    if sha256(jar) != TOOL_SHA256:
        raise GateError(f"{jar}: digest is not the pinned TLC 1.7.4; no model was checked")
    return jar


# ------------------------------------------------------------------ main

def gate(root: Path, runner: Runner, check_symbols: bool = True) -> dict:
    data = load_registry(root)
    fresh = record(data, root)
    errors = []
    try:
        committed = json.loads(read(root / SNAPSHOT))
    except json.JSONDecodeError as error:
        raise GateError(f"{SNAPSHOT}: {error}") from error
    amended = {a["module"] for a in data.get("amend", [])}
    errors += weakenings(committed, fresh, amended)
    if committed != fresh:
        errors.append(f"{SNAPSHOT} is stale; run tools/tlc_gate.py --update and review the diff")
    text = read(root / DOCS)
    start, end = docs_section(text)
    if text[start:end] != docs_table(data):
        errors.append(f"{DOCS}: protocol table is stale; run tools/tlc_gate.py --update")
    if check_symbols:
        errors += check_mapping(data, root)
    results = run_models(data, root, runner)
    errors += [f"{r['config']}: expected {'a violation of ' + r['expected_violation'] if r['expected_violation'] else 'no error'}"
               for r in results if not r["passed"]]
    return {"scope": "bounded TLC model checks; badge model-proved at most",
            "tool_sha256": TOOL_SHA256, "passed": not errors, "errors": errors, "cases": results}


def update(root: Path) -> None:
    data = load_registry(root)
    fresh = record(data, root)
    path = root / SNAPSHOT
    if path.exists():
        found = weakenings(json.loads(read(path)), fresh, {a["module"] for a in data.get("amend", [])})
        if found:
            raise GateError("refusing to record a weakened registry without [[amend]]:\n  " + "\n  ".join(found))
    path.write_text(json.dumps(fresh, indent=2) + "\n", encoding="utf-8")
    text = read(root / DOCS)
    start, end = docs_section(text)
    (root / DOCS).write_text(text[:start] + docs_table(data) + text[end:], encoding="utf-8")


def main(argv: list[str]) -> int:
    try:
        if argv == ["--update"]:
            update(ROOT)
            return 0
        if argv:
            raise GateError(__doc__ or "usage")
        report = gate(ROOT, tlc_runner(jar_from_env()))
    except GateError as error:
        print(f"tlc gate: FAILED: {error}", file=sys.stderr)
        return 1
    evidence = Path(os.environ.get(EVIDENCE_ENV, ROOT / "evidence-out"))
    evidence.mkdir(parents=True, exist_ok=True)
    (evidence / "models.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    for case in report["cases"]:
        print(f"{case['config']}: {'ok' if case['passed'] else 'FAIL'} ({case['distinct_states']} distinct states)")
    for error in report["errors"]:
        print(f"tlc gate: {error}", file=sys.stderr)
    print(f"tlc gate: {'passed' if report['passed'] else 'FAILED'}")
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
