//! The assurance manifest and the `prove`, `verify` and `correspondence`
//! gates (V-02, V-05, #91). `assurance/claims.toml` binds every handover
//! claim id of the frozen `formal/claims.json` to recorded Lean theorems
//! (`proofs/claims.json`), mapped TLC models (`models/claims.json`) and
//! runtime tests that exist; the generated table in `docs/TAUTEN.md` is
//! rewritten by `cargo xtask assurance --update`.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::Command;

use serde::Deserialize;
use serde_json::Value;

const MANIFEST: &str = "assurance/claims.toml";
const FORMAL: &str = "formal/claims.json";
const PROOFS: &str = "proofs/claims.json";
const PROOF_REGISTRY: &str = "proofs/claims.toml";
const MODELS: &str = "models/claims.json";
const RECORD: &str = "docs/TAUTEN.md";
const BEGIN: &str = "<!-- assurance:begin (generated by cargo xtask assurance --update) -->";
const END: &str = "<!-- assurance:end -->";

/// The machine-level invariants `prove` requires (#89, #90, #91): each
/// holds in every reachable state of its machine.
pub const MACHINE_INVARIANTS: &[&str] = &[
    "Proofs.Save.reachable_inv",
    "Proofs.Save.single_flight",
    "Proofs.Save.ack_monotone",
    "Proofs.Save.failed_tail_named",
    "Proofs.Save.clean_exit_needs_final_ack",
    "Proofs.Session.reachable_clock",
    "Proofs.Session.completed_is_stable",
    "Proofs.Request.applied_once",
    "Proofs.Barrier.done_is_drained",
    "Proofs.Ticket.accepted_fresh",
    "Proofs.Ticket.completion_retained",
    "Proofs.Queue.served_within_rank_plus_one",
];

#[derive(Debug, Deserialize)]
struct Manifest {
    claim: Vec<Entry>,
}

#[derive(Debug, Deserialize)]
struct Entry {
    id: String,
    claim: String,
    lean: Vec<String>,
    models: Vec<String>,
    runtime_tests: Vec<String>,
    status: String,
    assumptions: Vec<String>,
}

fn root() -> Result<PathBuf, String> {
    crate::dist::root()
}

fn read(root: &Path, path: &str) -> Result<String, String> {
    std::fs::read_to_string(root.join(path)).map_err(|error| format!("{path}: {error}"))
}

fn json(root: &Path, path: &str) -> Result<Value, String> {
    serde_json::from_str(&read(root, path)?).map_err(|error| format!("{path}: {error}"))
}

fn manifest(root: &Path) -> Result<Manifest, String> {
    toml::from_str(&read(root, MANIFEST)?).map_err(|error| format!("{MANIFEST}: {error}"))
}

/// Every theorem of a recorded `proved` claim whose mutants were all killed.
fn proved_theorems(proofs: &Value) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for claim in proofs
        .get("claims")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let proved = claim.get("outcome").and_then(Value::as_str) == Some("proved");
        let killed = claim
            .get("mutant_results")
            .and_then(Value::as_array)
            .is_none_or(|results| {
                results
                    .iter()
                    .all(|r| r.get("status").and_then(Value::as_str) == Some("killed"))
            });
        if proved && killed {
            for theorem in claim
                .get("theorems")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
            {
                if let Some(name) = theorem.as_str() {
                    out.insert(name.to_string());
                }
            }
        }
    }
    out
}

fn mapped_models(models: &Value) -> BTreeSet<String> {
    models
        .get("models")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter(|m| m.get("status").and_then(Value::as_str) == Some("mapped"))
        .filter_map(|m| m.get("module").and_then(Value::as_str).map(str::to_string))
        .collect()
}

/// `cargo test -- --list` for each package named, as "<package>::<test>".
fn listed_tests(root: &Path, packages: &BTreeSet<String>) -> Result<BTreeSet<String>, String> {
    let mut out = BTreeSet::new();
    for package in packages {
        let output = Command::new("cargo")
            .args([
                "test", "--locked", "-q", "-p", package, "--", "--list", "--format", "terse",
            ])
            .current_dir(root)
            .output()
            .map_err(|error| format!("cargo test --list: {error}"))?;
        if !output.status.success() {
            return Err(format!(
                "cargo test --list for {package} failed: {}",
                String::from_utf8_lossy(&output.stderr)
            ));
        }
        for line in String::from_utf8_lossy(&output.stdout).lines() {
            if let Some(name) = line.strip_suffix(": test") {
                out.insert(format!("{package}::{name}"));
            }
        }
    }
    Ok(out)
}

fn package_of(test: &str) -> Option<&str> {
    test.split_once("::").map(|(package, _)| package)
}

/// The manifest's errors against the recorded evidence; empty when sound.
fn check_entries(
    manifest: &Manifest,
    formal: &Value,
    proved: &BTreeSet<String>,
    mapped: &BTreeSet<String>,
    tests: &BTreeSet<String>,
) -> Vec<String> {
    let mut errors = Vec::new();
    let ids: BTreeSet<&str> = formal
        .get("claims")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|c| c.get("id").and_then(Value::as_str))
        .collect();
    let entries: BTreeMap<&str, &Entry> =
        manifest.claim.iter().map(|e| (e.id.as_str(), e)).collect();
    for id in &ids {
        if !entries.contains_key(id) {
            errors.push(format!("{id}: no entry in {MANIFEST}"));
        }
    }
    for entry in &manifest.claim {
        let id = &entry.id;
        if !ids.contains(id.as_str()) {
            errors.push(format!("{id}: not a handover claim id of {FORMAL}"));
        }
        for theorem in &entry.lean {
            if !proved.contains(theorem) {
                errors.push(format!(
                    "{id}: {theorem} is not recorded proved in {PROOFS}"
                ));
            }
        }
        for model in &entry.models {
            if !mapped.contains(model) {
                errors.push(format!("{id}: model {model} is not mapped in {MODELS}"));
            }
        }
        if entry.runtime_tests.is_empty() {
            errors.push(format!("{id}: names no runtime test"));
        }
        for test in &entry.runtime_tests {
            if !tests.contains(test) {
                errors.push(format!("{id}: runtime test {test} does not exist"));
            }
        }
        match entry.status.as_str() {
            "proved" if entry.lean.is_empty() => {
                errors.push(format!("{id}: `proved` with no theorem"));
            }
            "model-proved" if entry.models.is_empty() => {
                errors.push(format!("{id}: `model-proved` with no model"));
            }
            "tested" if !entry.lean.is_empty() || !entry.models.is_empty() => {
                errors.push(format!(
                    "{id}: `tested` while naming proofs or models; state their status"
                ));
            }
            "proved" | "model-proved" | "tested" => {}
            other => errors.push(format!("{id}: unknown status {other:?}")),
        }
    }
    errors
}

fn short(theorem: &str) -> String {
    theorem
        .strip_prefix("Proofs.")
        .unwrap_or(theorem)
        .to_string()
}

fn table(manifest: &Manifest) -> String {
    let mut out = String::from(BEGIN);
    out.push_str("\n\n| Id | Claim | Status | Lean | Models | Runtime tests | Assumptions |\n");
    out.push_str("|---|---|---|---|---|---|---|\n");
    let code = |items: Vec<String>| -> String {
        if items.is_empty() {
            "none".to_string()
        } else {
            items
                .iter()
                .map(|i| format!("`{i}`"))
                .collect::<Vec<_>>()
                .join("<br>")
        }
    };
    for entry in &manifest.claim {
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {} |\n",
            entry.id,
            entry.claim,
            entry.status,
            code(entry.lean.iter().map(|t| short(t)).collect()),
            code(entry.models.clone()),
            code(entry.runtime_tests.clone()),
            if entry.assumptions.is_empty() {
                "none".to_string()
            } else {
                entry.assumptions.join(" ")
            }
        ));
    }
    out.push('\n');
    out.push_str(END);
    out
}

fn with_table(record: &str, table: &str) -> Result<String, String> {
    let (before, rest) = record
        .split_once(BEGIN)
        .ok_or_else(|| format!("{RECORD}: no assurance table marker"))?;
    let (_, after) = rest
        .split_once(END)
        .ok_or_else(|| format!("{RECORD}: no assurance table end marker"))?;
    Ok(format!("{before}{table}{after}"))
}

/// `cargo xtask assurance [--update]`.
///
/// # Errors
/// Every manifest error, or a stale table without `--update`.
pub fn check(args: &[String]) -> Result<(), String> {
    let update = args.iter().any(|a| a == "--update");
    let root = root()?;
    let manifest = manifest(&root)?;
    let packages: BTreeSet<String> = manifest
        .claim
        .iter()
        .flat_map(|e| e.runtime_tests.iter())
        .filter_map(|t| package_of(t).map(str::to_string))
        .collect();
    let errors = check_entries(
        &manifest,
        &json(&root, FORMAL)?,
        &proved_theorems(&json(&root, PROOFS)?),
        &mapped_models(&json(&root, MODELS)?),
        &listed_tests(&root, &packages)?,
    );
    let record = read(&root, RECORD)?;
    let fresh = with_table(&record, &table(&manifest))?;
    if update && fresh != record {
        std::fs::write(root.join(RECORD), &fresh).map_err(|e| format!("{RECORD}: {e}"))?;
        println!("assurance: rewrote the table in {RECORD}");
    } else if !update && fresh != record {
        return Err(format!(
            "{RECORD}: the assurance table is stale; run `cargo xtask assurance --update`"
        ));
    }
    if errors.is_empty() {
        println!(
            "assurance: {} claims bound to recorded evidence",
            manifest.claim.len()
        );
        Ok(())
    } else {
        Err(format!("assurance failed:\n  {}", errors.join("\n  ")))
    }
}

/// The `prove` gate: every machine-level invariant is recorded proved.
///
/// # Errors
/// A missing or unproved invariant.
pub fn prove() -> Result<(), String> {
    let root = root()?;
    let proved = proved_theorems(&json(&root, PROOFS)?);
    let missing: Vec<&str> = MACHINE_INVARIANTS
        .iter()
        .copied()
        .filter(|t| !proved.contains(*t))
        .collect();
    if missing.is_empty() {
        println!(
            "prove: {} machine invariants recorded proved",
            MACHINE_INVARIANTS.len()
        );
        Ok(())
    } else {
        Err(format!(
            "prove: not recorded proved: {}",
            missing.join(", ")
        ))
    }
}

/// The `verify` gate: the recorded Lean claims belong to this commit's
/// kernel and proofs: every registered claim is recorded proved with every
/// mutant killed, and nothing they cover changed since the recorded commit.
///
/// # Errors
/// A claim not recorded or not proved, or changes since the record.
pub fn verify() -> Result<(), String> {
    let root = root()?;
    let proofs = json(&root, PROOFS)?;
    let registry: toml::Value = toml::from_str(&read(&root, PROOF_REGISTRY)?)
        .map_err(|e| format!("{PROOF_REGISTRY}: {e}"))?;
    let recorded: BTreeMap<String, &Value> = proofs
        .get("claims")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|c| Some((c.get("function")?.as_str()?.to_string(), c)))
        .collect();
    let mut errors = Vec::new();
    for claim in registry
        .get("claim")
        .and_then(toml::Value::as_array)
        .into_iter()
        .flatten()
    {
        let Some(function) = claim.get("function").and_then(toml::Value::as_str) else {
            continue;
        };
        match recorded.get(function) {
            None => errors.push(format!("{function}: not recorded in {PROOFS}")),
            Some(record) => {
                if record.get("outcome").and_then(Value::as_str) != Some("proved") {
                    errors.push(format!("{function}: recorded outcome is not proved"));
                }
                let want: BTreeSet<&str> = claim
                    .get("theorems")
                    .and_then(toml::Value::as_array)
                    .into_iter()
                    .flatten()
                    .filter_map(toml::Value::as_str)
                    .collect();
                let have: BTreeSet<&str> = record
                    .get("theorems")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .filter_map(Value::as_str)
                    .collect();
                if want != have {
                    errors.push(format!(
                        "{function}: the recorded theorems differ from the registry"
                    ));
                }
            }
        }
    }
    let commit = proofs
        .get("commit")
        .and_then(Value::as_str)
        .ok_or_else(|| format!("{PROOFS}: no recorded commit"))?;
    let diff = Command::new("git")
        .args([
            "diff",
            "--quiet",
            commit,
            "HEAD",
            "--",
            "crates/kernel/src",
            "crates/kernel/Cargo.toml",
            "proofs/Proofs",
            "proofs/Proofs.lean",
            "proofs/Extracted",
            PROOF_REGISTRY,
        ])
        .current_dir(&root)
        .status()
        .map_err(|e| format!("git diff: {e}"))?;
    if !diff.success() {
        errors.push(format!(
            "the kernel or proofs changed since the recorded commit {commit}; run `cargo +1.98.0 tauten proofs`"
        ));
    }
    if errors.is_empty() {
        println!(
            "verify: {} claims recorded proved for {commit}",
            recorded.len()
        );
        Ok(())
    } else {
        Err(format!("verify failed:\n  {}", errors.join("\n  ")))
    }
}

/// The `correspondence` gate: the manifest binds every claim, then every
/// runtime test it names runs and passes.
///
/// # Errors
/// A manifest error or a failing test.
pub fn correspondence() -> Result<(), String> {
    check(&[])?;
    let root = root()?;
    let manifest = manifest(&root)?;
    let mut by_package: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for test in manifest.claim.iter().flat_map(|e| e.runtime_tests.iter()) {
        if let Some((package, name)) = test.split_once("::") {
            by_package
                .entry(package.to_string())
                .or_default()
                .push(name.to_string());
        }
    }
    for (package, names) in by_package {
        for name in names {
            let status = Command::new("cargo")
                .args([
                    "test", "--locked", "-q", "-p", &package, "--", "--exact", &name,
                ])
                .current_dir(&root)
                .status()
                .map_err(|e| format!("cargo test: {e}"))?;
            if !status.success() {
                return Err(format!("correspondence: {package}::{name} failed"));
            }
        }
    }
    println!("correspondence: every named runtime test passed");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> (
        Manifest,
        Value,
        BTreeSet<String>,
        BTreeSet<String>,
        BTreeSet<String>,
    ) {
        let manifest: Manifest = toml::from_str(
            r#"
[[claim]]
id = "VP-01"
claim = "async admission"
lean = ["Proofs.Ticket.accept_iff_fresh"]
models = ["WorkerResults"]
runtime_tests = ["cadence-engine::a_duplicate_result_applies_once"]
status = "proved"
assumptions = []
"#,
        )
        .unwrap_or_else(|e| panic!("{e}"));
        let formal = serde_json::json!({"claims": [{"id": "VP-01"}]});
        let proved = BTreeSet::from(["Proofs.Ticket.accept_iff_fresh".to_string()]);
        let mapped = BTreeSet::from(["WorkerResults".to_string()]);
        let tests = BTreeSet::from(["cadence-engine::a_duplicate_result_applies_once".to_string()]);
        (manifest, formal, proved, mapped, tests)
    }

    #[test]
    fn a_sound_manifest_passes() {
        let (m, f, p, mo, t) = fixture();
        assert_eq!(check_entries(&m, &f, &p, &mo, &t), Vec::<String>::new());
    }

    /// #91 acceptance: removing a theorem from the record, or renaming a
    /// runtime test, fails; so does a handover id without an entry.
    #[test]
    fn missing_evidence_fails() {
        let (m, f, _, mo, t) = fixture();
        assert!(!check_entries(&m, &f, &BTreeSet::new(), &mo, &t).is_empty());
        let (m, f, p, mo, _) = fixture();
        let renamed = BTreeSet::from(["cadence-engine::a_renamed_test".to_string()]);
        assert!(!check_entries(&m, &f, &p, &mo, &renamed).is_empty());
        let (m, _, p, mo, t) = fixture();
        let more = serde_json::json!({"claims": [{"id": "VP-01"}, {"id": "VP-02"}]});
        assert!(!check_entries(&m, &more, &p, &mo, &t).is_empty());
        let (m, f, p, _, t) = fixture();
        assert!(!check_entries(&m, &f, &p, &BTreeSet::new(), &t).is_empty());
    }

    #[test]
    fn the_table_replaces_only_its_section() -> Result<(), String> {
        let (m, ..) = fixture();
        let record = format!("a\n{BEGIN}\nold\n{END}\nb\n");
        let out = with_table(&record, &table(&m))?;
        assert!(out.starts_with("a\n") && out.ends_with("\nb\n"));
        assert!(out.contains("| VP-01 | async admission | proved |"));
        Ok(())
    }
}
